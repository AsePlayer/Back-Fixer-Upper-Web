import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--portfolio')) {
  throw new Error('Usage: node scripts/sync-portfolio.mjs [--portfolio "path/to/Portfolio 2.0"]');
}
const portfolioRoot = fs.realpathSync(args[1] || path.join(appRoot, '..', 'Portfolio 2.0'));
const output = path.join(appRoot, 'dist');
const project = path.join(portfolioRoot, 'projects', 'stretch-finder');
const marker = '.generated-project.json';
const identity = 'back-fixer-upper-web';

// Check the selected portfolio and the exact owned directory before removing files.
const content = JSON.parse(fs.readFileSync(path.join(portfolioRoot, 'data', 'site.json'), 'utf8'));
if (!fs.existsSync(path.join(portfolioRoot, 'scripts', 'build.mjs')) ||
    !content.projects?.items?.some(item => item.id === 'stretch-finder' && item.href === '/projects/stretch-finder/')) {
  throw new Error('The selected portfolio must have the stretch-finder project card configured first.');
}
if (!fs.existsSync(path.join(output, 'index.html')) || !fs.existsSync(path.join(output, 'sw.js'))) {
  throw new Error('Build the app before syncing: npm run build');
}
const manifest = JSON.parse(fs.readFileSync(path.join(output, 'data', 'manifest.json'), 'utf8'));

function checkDirectory(directory) {
  const relative = path.relative(portfolioRoot, directory);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Destination must stay inside the portfolio.');
  let current = portfolioRoot;
  for (const segment of relative.split(path.sep)) {
    current = path.join(current, segment);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) throw new Error(`Refusing linked directory: ${current}`);
  }
}

checkDirectory(project);
if (fs.existsSync(project)) {
  const previous = path.join(project, marker);
  if (!fs.existsSync(previous) || JSON.parse(fs.readFileSync(previous, 'utf8')).source !== identity) {
    throw new Error('Refusing to replace a project directory that was not generated by this command.');
  }
}
const staging = path.join(portfolioRoot, '.tmp', `stretch-finder-${process.pid}`);
checkDirectory(staging);
if (fs.existsSync(staging)) throw new Error('A staging directory already exists; refusing to replace it.');
fs.mkdirSync(staging, {recursive: true});
fs.cpSync(output, staging, {recursive: true, dereference: false});
fs.writeFileSync(path.join(staging, marker), JSON.stringify({source: identity, catalogRevision: manifest.revision}, null, 2) + '\n');

// A normal link back keeps the complete app in its own page on the portfolio URL.
const html = fs.readFileSync(path.join(staging, 'index.html'), 'utf8');
const anchor = '<header class="site-header">';
if (!html.includes(anchor)) throw new Error('App header changed; review the portfolio return link before syncing.');
fs.writeFileSync(path.join(staging, 'index.html'), html.replace(anchor,
  `${anchor}<a class="portfolio-return" href="../../#projects">&larr; Portfolio</a>`));
// Include the return link in the shell cache's version, even if app assets did not change.
const workerPath = path.join(staging, 'sw.js');
const worker = fs.readFileSync(workerPath, 'utf8');
if (!/const VERSION='[^']+'/.test(worker)) throw new Error('Service worker changed; review shell version generation before syncing.');
const hash = createHash('sha256');
for (const file of ['index.html', 'favicon.svg', ...fs.readdirSync(path.join(staging, 'assets')).map(file => `assets/${file}`)]) {
  hash.update(fs.readFileSync(path.join(staging, file)));
}
fs.writeFileSync(workerPath, worker.replace(/const VERSION='[^']+'/, `const VERSION='${hash.digest('hex').slice(0, 16)}'`));

checkDirectory(project);
fs.mkdirSync(path.dirname(project), {recursive: true});
if (fs.existsSync(project)) fs.rmSync(project, {recursive: true, force: true});
fs.renameSync(staging, project);
console.log(`Synced generated app to ${project}`);
console.log('Next: in Portfolio 2.0, run node scripts/build.mjs and node scripts/validate-site.mjs.');
console.log('Edit app source in Health Stretch App; edit the project card in Portfolio 2.0/data/site.json.');
